-- Books: Arche Aviation Pte. Ltd.'s own accounts (Morten, 10 Nov 2026: "for me and my wife only ... our own accounting
-- section in the portal ... think quickbooks or similar, but singapore regulations ... any transaction should
-- automatically be updating our books live ... password protected a second security layer ... options to share with
-- bookkeeping and accounting as non-owners ... daily backup ... suggest optimizations ... NO decisions can be made").
--
-- Security model (docs/BOOKS.md):
--  * Every books table has row-level security on and NO policy, and anon/authenticated lose all rights: no browser can
--    read or write them directly. Only the server (api/_books, secret key) does, after it has checked the portal
--    sign-in, the person's books right (owners come from the BOOKS_OWNERS setting in Vercel, not from the database) and a
--    second factor (passkey or authenticator code) used within the last 15 minutes.
--  * Posted entries can never be changed or deleted, by anyone, the server included (triggers below). A mistake is put
--    right by a reversing entry. Every entry carries the hash of the one before it, so a change made outside the
--    portal would break the chain, and acct_verify() finds it.
--  * The portal's money steps post themselves (triggers on trip_status and payouts); a posting that fails never
--    blocks the portal: it is kept in acct_errors and shown in Books.
-- Safe to run twice.

