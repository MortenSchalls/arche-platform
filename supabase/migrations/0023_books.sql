    revoke execute on function public.acct_verify() from anon, authenticated, public;
    revoke execute on function public.acct_ref_balance(text, text) from anon, authenticated, public;
    revoke execute on function public.reset_identities() from anon, authenticated, public;
  end if;
end $$;
