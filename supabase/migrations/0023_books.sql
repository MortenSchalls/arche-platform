-- ---------- the ledger ----------
create table if not exists public.acct_journal (
  id bigint generated by default as identity primary key,
  entity text not null default 'arche-aviation',
  jdate date not null,
  memo text not null default '',
  source text unique,                          -- portal event key; the same event is never posted twice
  kind text not null default 'manual' check (kind in ('auto','manual','reversal','opening','import')),
  reverses bigint references public.acct_journal(id),
  created_by uuid,
  created_at timestamptz not null default now(),
  prev_hash text not null,
  hash text not null unique
);
create table if not exists public.acct_lines (
  id bigint generated by default as identity primary key,
  journal_id bigint not null references public.acct_journal(id),
  account text not null references public.acct_accounts(code),
  debit numeric(16,2) not null default 0 check (debit >= 0),
  credit numeric(16,2) not null default 0 check (credit >= 0),
  memo text not null default '',
  ref text not null default '',               -- trip, payout or bank line the amount belongs to
  check (debit = 0 or credit = 0),
  check (debit + credit > 0)
);
create index if not exists acct_lines_journal on public.acct_lines (journal_id);
create index if not exists acct_lines_account on public.acct_lines (account);
create index if not exists acct_lines_ref on public.acct_lines (ref);
create index if not exists acct_journal_date on public.acct_journal (jdate);

