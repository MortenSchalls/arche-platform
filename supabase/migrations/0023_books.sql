-- ---------- posting ----------
create or replace function public.acct_num(x text) returns numeric language sql immutable as $$
  select case when x ~ '^\s*-?[0-9]+(\.[0-9]+)?\s*$' then round(x::numeric, 2) else 0 end $$;
create or replace function public.acct_date(x text) returns date language sql stable as $$
  select case when x ~ '^\d{4}-\d{2}-\d{2}' then substr(x, 1, 10)::date else current_date end $$;
-- one entry: lines = [{account, debit, credit, memo, ref}]; balanced, at least two lines, accounts that exist
create or replace function public.acct_post(p_date date, p_memo text, p_source text, p_kind text, p_lines jsonb,
                                            p_by uuid default null, p_reverses bigint default null)
returns bigint language plpgsql security definer set search_path = public as $$
declare jid bigint; prev text; h text; dr numeric := 0; cr numeric := 0; l jsonb; canon text := ''; n int := 0;
begin
  perform pg_advisory_xact_lock(87230231);
  if p_source is not null then select id into jid from acct_journal where source = p_source; if found then return jid; end if; end if;
  if jsonb_typeof(p_lines) <> 'array' then raise exception 'Books: lines missing'; end if;
  for l in select * from jsonb_array_elements(p_lines) loop
    n := n + 1;
    if not exists (select 1 from acct_accounts a where a.code = l->>'account' and a.active) then raise exception 'Books: unknown account %', l->>'account'; end if;
    if coalesce((l->>'debit')::numeric, 0) < 0 or coalesce((l->>'credit')::numeric, 0) < 0 then raise exception 'Books: negative amount'; end if;
    dr := dr + round(coalesce((l->>'debit')::numeric, 0), 2); cr := cr + round(coalesce((l->>'credit')::numeric, 0), 2);
    if round(coalesce((l->>'debit')::numeric, 0), 2) + round(coalesce((l->>'credit')::numeric, 0), 2) = 0 then raise exception 'Books: a line has no amount'; end if;
    if round(coalesce((l->>'debit')::numeric, 0), 2) > 0 and round(coalesce((l->>'credit')::numeric, 0), 2) > 0 then raise exception 'Books: a line has both a debit and a credit'; end if;
    canon := canon || (l->>'account') || ':' || round(coalesce((l->>'debit')::numeric, 0), 2) || ':' || round(coalesce((l->>'credit')::numeric, 0), 2) || ':' || left(coalesce(l->>'ref', ''), 120) || ';';
  end loop;
  if n < 2 then raise exception 'Books: an entry needs at least two lines'; end if;
  if p_kind not in ('auto','manual','reversal','opening','import') then raise exception 'Books: unknown kind'; end if;
  if dr <> cr or dr = 0 then raise exception 'Books: debits % and credits % do not balance', dr, cr; end if;
  select hash into prev from acct_journal order by id desc limit 1;
  prev := coalesce(prev, 'genesis');
  h := encode(sha256(convert_to(prev || '|' || p_date || '|' || left(coalesce(p_memo, ''), 300) || '|' || coalesce(p_source, '') || '|' || p_kind || '|' || coalesce(p_reverses::text, '') || '|' || canon, 'UTF8')), 'hex');
  insert into acct_journal (jdate, memo, source, kind, reverses, created_by, prev_hash, hash)
    values (p_date, left(coalesce(p_memo, ''), 300), p_source, p_kind, p_reverses, p_by, prev, h) returning id into jid;
  insert into acct_lines (journal_id, account, debit, credit, memo, ref)
    select jid, x->>'account', round(coalesce((x->>'debit')::numeric, 0), 2), round(coalesce((x->>'credit')::numeric, 0), 2),
           left(coalesce(x->>'memo', ''), 200), left(coalesce(x->>'ref', ''), 120)
    from jsonb_array_elements(p_lines) x
    where round(coalesce((x->>'debit')::numeric, 0), 2) + round(coalesce((x->>'credit')::numeric, 0), 2) > 0;
  return jid;
end $$;

-- a reversing entry: every line of the original with debit and credit swapped
create or replace function public.acct_reverse(p_id bigint, p_date date, p_memo text, p_by uuid) returns bigint
language plpgsql security definer set search_path = public as $$
declare ls jsonb;
begin
  if exists (select 1 from acct_journal where reverses = p_id) then raise exception 'Books: entry % is already reversed', p_id; end if;
  select jsonb_agg(jsonb_build_object('account', account, 'debit', credit, 'credit', debit, 'memo', memo, 'ref', ref)) into ls from acct_lines where journal_id = p_id;
  if ls is null then raise exception 'Books: entry % not found', p_id; end if;
  return acct_post(p_date, coalesce(nullif(p_memo, ''), 'Reversal of entry ' || p_id), 'reverse:' || p_id, 'reversal', ls, p_by, p_id);
end $$;

-- the hash chain: returns the first entry whose hash does not match, or nothing when the books are intact
create or replace function public.acct_verify() returns table (bad_id bigint, reason text)
language plpgsql stable security definer set search_path = public as $$
declare j record; prev text := 'genesis'; canon text; h text;
begin
  for j in select * from acct_journal order by id loop
    if j.prev_hash <> prev then bad_id := j.id; reason := 'chain broken'; return next; return; end if;
    select string_agg(account || ':' || debit || ':' || credit || ':' || ref || ';', '' order by id) into canon from acct_lines where journal_id = j.id;
    h := encode(sha256(convert_to(j.prev_hash || '|' || j.jdate || '|' || j.memo || '|' || coalesce(j.source, '') || '|' || j.kind || '|' || coalesce(j.reverses::text, '') || '|' || coalesce(canon, ''), 'UTF8')), 'hex');
    if h <> j.hash then bad_id := j.id; reason := 'entry changed'; return next; return; end if;
    prev := j.hash;
  end loop;
end $$;

-- balance of one account for one reference (a trip's client money)
create or replace function public.acct_ref_balance(p_account text, p_ref text) returns numeric language sql stable security definer set search_path = public as $$
  select coalesce(sum(credit - debit), 0) from acct_lines where account = p_account and ref = p_ref $$;

-- ---------- live posting from the portal's money steps ----------
-- Trip money (trip_status.data): receipts[] = client money cleared (or clientPaid with price), payouts[] = operator paid
-- (or operatorPaid with opPrice). Client money sits in 2100 per trip until the last leg is flown; then what is left of
-- it (received less paid to the operator) is Archē's margin. Anything received or paid after the flight trues it up.
create or replace function public.acct_trip_post() returns trigger language plpgsql security definer set search_path = public as $$
declare d jsonb := new.data; k text := 'trip:' || new.owner_id || ':' || new.id; ref text := coalesce(nullif(new.data->>'ref', ''), new.id);
        x jsonb; i int; amt numeric; bal numeric; nrev int;
begin
  begin
    if jsonb_typeof(d->'receipts') = 'array' and jsonb_array_length(d->'receipts') > 0 then
      i := 0;
      for x in select * from jsonb_array_elements(d->'receipts') loop
        i := i + 1; amt := acct_num(x->>'amount');
        if amt > 0 then perform acct_post(acct_date(x->>'date'), 'Client money cleared: ' || ref, k || ':r:' || coalesce(x->>'at', i::text) || ':' || amt, 'auto',
          jsonb_build_array(jsonb_build_object('account','1100','debit',amt,'ref',k), jsonb_build_object('account','2100','credit',amt,'ref',k))); end if;
      end loop;
    elsif coalesce(d->>'clientPaid', '') = 'true' and acct_num(d->>'price') > 0 then
      amt := acct_num(d->>'price');
      perform acct_post(acct_date(d->>'clientPaidDate'), 'Client paid: ' || ref, k || ':client', 'auto',
        jsonb_build_array(jsonb_build_object('account','1100','debit',amt,'ref',k), jsonb_build_object('account','2100','credit',amt,'ref',k)));
    end if;
    if jsonb_typeof(d->'payouts') = 'array' and jsonb_array_length(d->'payouts') > 0 then
      i := 0;
      for x in select * from jsonb_array_elements(d->'payouts') loop
        i := i + 1; amt := acct_num(x->>'amount');
        if amt > 0 then perform acct_post(acct_date(x->>'date'), 'Operator paid: ' || ref, k || ':p:' || coalesce(x->>'at', i::text) || ':' || amt, 'auto',
          jsonb_build_array(jsonb_build_object('account','2100','debit',amt,'ref',k), jsonb_build_object('account','1100','credit',amt,'ref',k))); end if;
      end loop;
    elsif coalesce(d->>'operatorPaid', '') = 'true' and acct_num(d->>'opPrice') > 0 then
      amt := acct_num(d->>'opPrice');
      perform acct_post(acct_date(d->>'operatorPaidDate'), 'Operator paid: ' || ref, k || ':operator', 'auto',
        jsonb_build_array(jsonb_build_object('account','2100','debit',amt,'ref',k), jsonb_build_object('account','1100','credit',amt,'ref',k)));
    end if;
    if coalesce(d->>'state', '') = 'flown' then
      bal := acct_ref_balance('2100', k);
      if bal <> 0 then
        select count(*) into nrev from acct_journal where source like k || ':margin:%';
        if bal > 0 then
          perform acct_post(acct_date(coalesce(d->>'flownDate', '')), 'Margin earned, trip flown: ' || ref, k || ':margin:' || (nrev + 1), 'auto',
            jsonb_build_array(jsonb_build_object('account','2100','debit',bal,'ref',k), jsonb_build_object('account','4000','credit',bal,'ref',k)));
        else
          perform acct_post(acct_date(coalesce(d->>'flownDate', '')), 'Check: operator paid more than the client on ' || ref, k || ':margin:' || (nrev + 1), 'auto',
            jsonb_build_array(jsonb_build_object('account','4000','debit',-bal,'ref',k), jsonb_build_object('account','2100','credit',-bal,'ref',k)));
        end if;
      end if;
    end if;
  exception when others then
    insert into acct_errors (source, message, data) values (k, left(sqlerrm, 300), jsonb_build_object('table', 'trip_status'));
  end;
  return new;
end $$;
drop trigger if exists acct_trip_post on public.trip_status;
create trigger acct_trip_post after insert or update on public.trip_status for each row execute function public.acct_trip_post();

-- commission paid out to a broker (payouts/{broker}/months/{month}: paid, amount, date, ref)
create or replace function public.acct_payout_post() returns trigger language plpgsql security definer set search_path = public as $$
declare k text := 'payout:' || new.owner_id || ':' || new.id; amt numeric := acct_num(new.data->>'amount');
begin
  begin
    if coalesce(new.data->>'paid', '') = 'true' and amt > 0 then
      perform acct_post(acct_date(new.data->>'date'), 'Commission paid out: ' || new.id || coalesce(' ref ' || nullif(new.data->>'ref', ''), ''), k, 'auto',
        jsonb_build_array(jsonb_build_object('account','5000','debit',amt,'ref',k), jsonb_build_object('account','1000','credit',amt,'ref',k)));
    end if;
  exception when others then
    insert into acct_errors (source, message, data) values (k, left(sqlerrm, 300), jsonb_build_object('table', 'payouts'));
  end;
  return new;
end $$;
drop trigger if exists acct_payout_post on public.payouts;
create trigger acct_payout_post after insert or update on public.payouts for each row execute function public.acct_payout_post();

-- after a restore: move every identity counter past the highest id put back, so new rows never collide
create or replace function public.reset_identities() returns void language plpgsql security definer set search_path = public as $$
declare t text;
begin
  foreach t in array array['audit_log','site_events','screen_log','acct_journal','acct_lines','acct_log','acct_errors'] loop
    if to_regclass('public.' || t) is not null then
      execute format('select setval(pg_get_serial_sequence(%L, ''id''), greatest((select coalesce(max(id), 0) from public.%I), 1))', 'public.' || t, t);
    end if;
  end loop;
end $$;

