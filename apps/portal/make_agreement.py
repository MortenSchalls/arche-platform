"""Builds src-modules/agreement-text.js from agreement/agreement-source.html (Morten, 24 Oct 2026).
The source is the signing version of the Independent Broker Consultancy Agreement, exported from the agreement doc.
Company details and the consultant's Schedule 2 come from the portal at signing; Schedules 2 and 3 are drawn by the portal.
After changing the agreement doc: replace agreement-source.html, raise VERSION, run  python3 make_agreement.py , then
paste the new src-modules/agreement-text.js over the old block in index.html."""
import json, pathlib, re
HERE = pathlib.Path(__file__).parent
VERSION = "2026-10-29.1"  # 4.4 refunds and chargebacks: only named cases, within 180 days, never a repayment, not for Archē's or the operator's fault (Morten, 29 Oct 2026). Earlier: 2026-10-26.3 (8.9 insurance; Schedule 1 supervision share; Schedule 4 meeting hosting and recording)
s = (HERE / "agreement" / "agreement-source.html").read_text(encoding="utf-8")
s = re.sub(r"<h1>.*?</h1>\s*", "", s, count=1)
s = re.sub(r'<p class="sub">.*?</p>\s*', "", s, count=1)
s = s.replace("(UEN [●]), whose registered office is at [●], Singapore", "(UEN {{UEN}}), whose registered office is at {{OFFICE}}", 1)
s = s.replace("is registered in Singapore, UEN [●], registered office [●].", "is registered in Singapore, UEN {{UEN}}, registered office {{OFFICE}}.", 1)
s = s.replace("[privacy email]", "{{PRIVACY}}")
a = s.index("<h2>Schedule 2: Consultant details</h2>"); b = s.index("<h2>Schedule 4:")
main, tail = s[:a], s[b:]
assert "[●]" not in main and "[●]" not in tail, "unfilled placeholder left in the agreement"
js = ("/* ---------- Agreement text (generated by make_agreement.py from agreement/agreement-source.html; do not edit here) ---------- */\n"
      f"const AGR_VERSION = {json.dumps(VERSION)};\nconst AGR_MAIN = {json.dumps(main, ensure_ascii=False)};\nconst AGR_TAIL = {json.dumps(tail, ensure_ascii=False)};\n")
(HERE / "src-modules" / "agreement-text.js").write_text(js, encoding="utf-8")
print("agreement-text.js", len(js))
