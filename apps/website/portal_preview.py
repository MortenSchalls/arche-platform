"""Private copy of the locked website inside the portal (Morten, 30 Oct 2026: "Give me access to the website through a
link in my portal, as I am logged in there I don't need to log in again ... I need you to do it and make it work").
Run by build.py at the end. Packs the built site (apps/website/site, without its api/ and logo-export/) into
apps/portal/api/_site/data.mjs: each file gzip-compressed, base64. Addresses are moved under /website/ so the copy works
at portal.archeaviation.com/website/. The portal serves it only to the signed-in owner (apps/portal/api/site.mjs);
the forms are switched off there. Nothing in api/ is served as a plain file, so the copy is not public."""
import os, re, gzip, base64, json
HERE = os.path.dirname(os.path.abspath(__file__)); SITE = os.path.join(HERE, "site")
OUT = os.path.join(HERE, "..", "portal", "api", "_site", "data.mjs")
TEXT = (".html", ".css", ".js", ".json", ".svg", ".xml", ".txt", ".webmanifest")
SKIP_DIRS = {"api", "logo-export"}
PATHS = r"api|services|aircraft|how-it-works|contact|destinations|img|assets|vendor|cities|regions|countries|airports|guides|nav\.css|track\.js|privacy\.html|terms\.html|i18n\.js|site-fixes\.css|support\.js|image-slot\.js|doc-page\.js|th|zh|ja"

def move(t):
    t = re.sub(r'((?:href|src|action)=["\'])/(?!/)', r"\1/website/", t)
    t = re.sub(r'url\((["\']?)/(?!/)', r"url(\1/website/", t)
    t = re.sub(r'(["\'`])/(' + PATHS + r')(?=[/"\'`?#.]|\b)', r"\1/website/\2", t)
    t = t.replace("l === 'en' ? '/' : '/' + l", "l === 'en' ? '/website/' : '/website/' + l")
    return t

def run(verbose=True):
    text = {}
    for root, dirs, files in os.walk(SITE):
        rel = os.path.relpath(root, SITE)
        if rel.split(os.sep)[0] in SKIP_DIRS: continue
        for f in files:
            if f.endswith(TEXT): text[os.path.normpath(os.path.join(rel, f)).replace(os.sep, "/").lstrip("./")] = open(os.path.join(root, f), encoding="utf-8").read()
    used = "\n".join(text.values())
    data = {}
    for root, dirs, files in os.walk(SITE):
        rel = os.path.relpath(root, SITE)
        if rel.split(os.sep)[0] in SKIP_DIRS: continue
        for f in files:
            p = os.path.normpath(os.path.join(rel, f)).replace(os.sep, "/").lstrip("./")
            if p in text: raw = move(text[p]).encode("utf-8")
            elif f in used: raw = open(os.path.join(root, f), "rb").read()   # pictures only if some page uses them
            else: continue
            data[p] = base64.b64encode(gzip.compress(raw, 9, mtime=0)).decode("ascii")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as o:
        o.write("// Generated by apps/website/portal_preview.py. Do not edit. Path -> gzip, base64.\nexport default {\n")
        for k in sorted(data): o.write(json.dumps(k) + ":" + json.dumps(data[k]) + ",\n")
        o.write("};\n")
    if verbose: print(f"  portal preview: {len(data)} files, {os.path.getsize(OUT) // 1024} KB")

if __name__ == "__main__": run()
